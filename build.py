"""Verify that the React files were committed before Vercel deploys Flask.

The production bundle is generated by GitHub Actions and committed under
public/. It must exist in the source checkout before Vercel starts packaging
its Python application and static files.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "public"


def verify_assets(output=OUTPUT):
    index = output / "index.html"
    if not index.is_file():
        raise RuntimeError("React bundle missing from repository: public/index.html")
    html = index.read_text(encoding="utf-8")
    if "STUDENTVERIFI_VITE_BUILD" not in html:
        raise RuntimeError("Unexpected React entrypoint: build marker missing")
    scripts = re.findall(r'(?:src|href)=["\'](/assets/[^"\']+\.js)["\']', html)
    if not scripts or not all((output / p.lstrip("/")).is_file() for p in scripts):
        raise RuntimeError("React JavaScript bundle referenced by index.html is missing")
    if not list((output / "assets").glob("*.css")):
        raise RuntimeError("React stylesheet is missing")
    print("StudentVerifi React assets verified: committed public/ bundle is ready", flush=True)


if __name__ == "__main__":
    verify_assets()
